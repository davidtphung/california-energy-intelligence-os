export const ALL_JURISDICTION_ABBRS: string[] = KEYSTONES.map((k) => k.abbr)

export function buildJurisdictionKeystonePolicies(): EnergyPolicy[] {
  return KEYSTONES.map((k) => ({
    id: `st-${k.abbr.toLowerCase()}-keystone`,
    year: k.year,
    title: k.title,
    short: k.short,
    level: k.abbr === 'DC' ? 'local' : 'state',
    jurisdiction: k.name,
    stateAbbr: k.abbr,
    era: k.era,
    status: k.status,
    themes: k.themes,
    summary: k.summary,
    impact: k.impact,
    instruments: k.instruments,
    cite: k.cite,
  }))
}

/** True if every state + DC + PR + GU + VI + AS + MP has at least one policy */
export function jurisdictionCoverage(policies: { stateAbbr?: string }[]): {
  covered: string[]
  missing: string[]
} {
  const have = new Set(
    policies.map((p) => p.stateAbbr).filter((a): a is string => Boolean(a))
  )
  const covered = ALL_JURISDICTION_ABBRS.filter((a) => have.has(a))
  const missing = ALL_JURISDICTION_ABBRS.filter((a) => !have.has(a))
  return { covered, missing }
}
